"""All-or-nothing batches of file and wallpapers.toml changes."""
from __future__ import annotations

import dataclasses
import os
import tempfile
import threading
from pathlib import Path
from typing import Callable

from ..domain.rules import TOML_NAME
from ..errors import NotFound
from .publish import BLOBS, blob_id
from ..ports import Catalogue, ImageStore, Vcs

__all__ = ["TOML_NAME", "UnitOfWork"]


# One lock for the whole process (single user, one server). Re-entrant: nested units join the outer one.
_LOCK = threading.RLock()
WRITE_LOCK = _LOCK  # every repository write (units of work, index-only git actions) runs under this one lock
_depth = 0
# (path, bytes before) -- None means "did not exist"; guarded by _LOCK
_undo: list[tuple[Path, bytes | None]] = []
_outer: "UnitOfWork | None" = None  # the outermost open unit; guarded by _LOCK
_owner: int | None = None  # thread holding the open unit; guarded by _LOCK


def in_unit() -> bool:
    """Whether the calling thread is inside a unit of work."""
    return _depth > 0 and _owner == threading.get_ident()


def _restore(path: Path, data: bytes | None) -> None:
    if data is None:
        try:
            path.unlink()
        except FileNotFoundError:
            pass
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".restore-", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
        if path.exists():
            os.chmod(tmp, path.stat().st_mode & 0o777)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except FileNotFoundError:
            pass
        raise


def record_index(path: Path) -> None:
    """The Vcs calls this before it writes a git index file (git add/mv/rm): inside a unit the index is snapshotted
    once, so a rollback restores it byte for byte with the recorded files (Ruling v2-17). Outside a unit: no-op."""
    if not in_unit() or _outer is None:
        return
    path = Path(path)
    if path in _outer._indexes:
        return
    _outer._indexes.add(path)
    try:
        before: bytes | None = path.read_bytes()
    except FileNotFoundError:
        before = None
    _undo.append((path, before))


class UnitOfWork:
    """`with UnitOfWork(...) as uow: uow.record_file(p); ...change p...`

    On an exception every recorded file and wallpapers.toml is restored byte for byte (reverse order) and the
    exception is re-raised. When the outermost block exits cleanly, `on_commit` runs once. Restoration writes the
    snapshotted bytes directly, so it is never blocked by the catalogue's structural refusal.
    """

    def __init__(self, catalogue: Catalogue, store: ImageStore, vcs: Vcs, on_commit: Callable[["UnitOfWork"], None],
                 regenerate=()) -> None:
        """`regenerate`: folders whose working TOML changed outside wallman since the last look (their index TOML is
        regenerated by this unit: published names whose entry is gone leave it)."""
        self.catalogue = catalogue
        self.store = store
        self.vcs = vcs
        self.on_commit = on_commit
        self._regenerate = tuple(regenerate)
        self._mark = 0
        self._stage = True
        self._touched: set[str] = set()
        self._paths: set[Path] = set()
        self._deferred: list[Path] = []
        self._force = False
        self._indexes: set[Path] = set()
        self._published: dict[str, set[str]] = {}  # folder -> published set (read from the index, or pending)
        self._regen: dict[str, None] = {}  # folders whose index wallpapers.toml is regenerated at commit
        self._ids: dict[str, str | None] = {}  # folder -> blob id of its index wallpapers.toml, read in this unit

    @property
    def stage(self) -> bool:
        """Whether on_commit may stage generated files; nested units share the outermost unit's value."""
        return (_outer or self)._stage

    @stage.setter
    def stage(self, value: bool) -> None:
        (_outer or self)._stage = value

    @property
    def touched(self) -> set[str]:
        """Collection folders (relative to the collection root) of every recorded file or collection, nested
        units included: what on_commit hands to the library index."""
        return (_outer or self)._touched

    @property
    def touched_paths(self) -> set[Path]:
        """Every recorded file (nested units included): the only files whose git state an operation can change,
        so the index asks git about these alone after the commit."""
        return (_outer or self)._paths

    def __enter__(self) -> "UnitOfWork":
        global _depth, _outer, _owner
        _LOCK.acquire()
        _depth += 1
        if _depth == 1:
            _outer = self
            _owner = threading.get_ident()
            self._stage = True
            self._touched = set()
            self._paths = set()
            self._deferred = []
            self._force = False
            self._indexes = set()
            self._published = {}
            self._regen = {}
            self._ids = {}
            for folder in self._regenerate:
                try:
                    self._flag(folder)
                except Exception:  # noqa: BLE001 -- a clean-up of stale names: never what blocks an operation
                    pass
        self._mark = len(_undo)
        return self

    def record_file(self, path: Path) -> None:
        path = Path(path)
        try:
            before: bytes | None = path.read_bytes()
        except FileNotFoundError:
            before = None
        _undo.append((path, before))
        self.touched_paths.add(path)
        self._touch(path)

    def stage_add(self, paths: list[Path], force: bool = False) -> None:
        """`git add` at commit time instead of now: on_commit can take them (take_staged) into the one `git add` it
        runs for the generated files, and whatever it leaves is added when the unit commits. Nothing is staged when
        the unit rolls back. `force`: the path may still be in .gitignore, so the whole batch is added with -f
        (harmless for the tomls and generated files, which are never ignored)."""
        outer = _outer or self
        outer._deferred.extend(Path(p) for p in paths)
        outer._force = outer._force or bool(force and paths)

    @property
    def stage_force(self) -> bool:
        """Whether the paths deferred so far must be added with -f (read it before take_staged)."""
        return (_outer or self)._force

    def take_staged(self) -> list[Path]:
        """The paths stage_add() deferred so far (they are then the caller's to stage, with -f when stage_force)."""
        outer = _outer or self
        paths, outer._deferred, outer._force = list(dict.fromkeys(outer._deferred)), [], False
        return paths

    # -- publish model: the index wallpapers.toml is generated --------------------------------------
    def published(self, folder: str) -> set[str]:
        """The files of `folder` whose entry is published, as this unit set it (set_published) or else as it stood
        when the unit first looked: the names in the index wallpapers.toml that still have an entry in the working
        one. A name whose entry left the working TOML is never published again by a new entry taking it (only
        publish, or a carried-over rename or move, publishes). The first look happens before the unit writes the
        folder's TOML (record_collection). A copy."""
        outer = _outer or self
        if folder not in outer._published:
            index_id = self._index_id(folder)
            try:
                working = {w.file for w in self.catalogue.load(folder).wallpapers}
            except NotFound:
                working = set()
            if index_id is None:
                files: set[str] = set()
            elif index_id == self._working_id(folder):
                files = working  # the index holds the working file itself: nothing to read
            else:
                toml = self.store.path(folder, TOML_NAME)
                names = BLOBS.get(index_id, lambda: self.catalogue.blob_entries(self.vcs.index_blob(toml) or b""))
                files = working & names.keys()
            outer._published[folder] = files
        return set(outer._published[folder])

    def _index_id(self, folder: str) -> str | None:
        """Read once per unit: only write_index changes it, and it runs at the very end."""
        outer = _outer or self
        if folder not in outer._ids:
            outer._ids[folder] = self.vcs.index_blob_id(self.store.path(folder, TOML_NAME))
        return outer._ids[folder]

    def _working_id(self, folder: str) -> str | None:
        try:
            return blob_id(self.store.path(folder, TOML_NAME).read_bytes())
        except OSError:
            return None

    def set_published(self, folder: str, files) -> None:
        """Make `files` the published set of `folder`; its index wallpapers.toml is regenerated at commit."""
        outer = _outer or self
        outer._published[folder] = set(files)
        outer._regen[folder] = None

    def stage_toml(self, folder: str) -> None:
        """What `git add wallpapers.toml` used to be: regenerate the index TOML at commit (current working values of
        the published entries). External collections keep staging their whole TOML in their own repository."""
        if self.store.is_external(folder):
            self.stage_add([self.store.path(folder, TOML_NAME)])
        else:
            self._flag(folder)

    def _flag(self, folder: str) -> None:
        """Regenerate the folder's index TOML at commit, from its published set as it stands now (never for an
        external collection, nor for a structurally broken TOML: see write_index)."""
        if self.store.is_external(folder) or self._broken(folder):
            return
        self.published(folder)
        (_outer or self)._regen[folder] = None

    def _broken(self, folder: str) -> bool:
        """The folder's working TOML has structural problems (load() skipped tables). No TOML: not broken."""
        try:
            return bool(self.catalogue.structural_issues(folder))
        except NotFound:
            return False

    def write_index(self) -> None:
        """Write the index wallpapers.toml of every folder marked so far: the working collection filtered to the
        published set (never a personal entry), rendered like the working file (count = published entries);
        removed from the index when nothing is published. A blob equal to the current one is not written again.
        on_commit calls it (after its last step that can fail); whatever is left is written when the unit
        commits."""
        outer = _outer or self
        while outer._regen:
            folder = next(iter(outer._regen))
            del outer._regen[folder]
            if self._broken(folder):
                # broken by hand: load() skipped some tables, so a regeneration would silently unpublish them.
                # The index TOML stays as it is until the file is fixed (the operations on the folder itself
                # refuse up front; the index and validate report the problem).
                continue
            published = self.published(folder)
            toml = self.store.path(folder, TOML_NAME)
            try:
                coll = self.catalogue.load(folder)
            except NotFound:
                coll = None
            # personal entries are never published. A wallpapers.toml once committed whole still lists them in the
            # index: the next regeneration drops them, so the next commit removes their metadata from the repository
            entries = [w for w in coll.wallpapers if w.file in published and w.license != "personal"] \
                if coll is not None else []
            current = self._index_id(folder)
            if not entries:
                if current is not None:
                    self.vcs.unstage_path(toml)
                continue
            if len(entries) == len(coll.wallpapers):
                # everything published, nothing personal: the index takes the working file itself, in the one
                # batched `git add` (no render, no hash-object of a 2 MB blob)
                if current != self._working_id(folder):
                    self.stage_add([toml])
                continue
            data, texts = self.catalogue.render_parts(dataclasses.replace(coll, wallpapers=entries))
            new = blob_id(data)
            if new != current:
                self.vcs.stage_blob(toml, data)
            BLOBS.put(new, texts)  # nobody reads it back: the next unit and the index states find it here
        outer._published, outer._ids = {}, {}  # the index changed: later reads go back to it

    def record_collection(self, folder: str) -> None:
        """Before the folder's working TOML is written: snapshot it, and regenerate its index TOML at commit (every
        write of a working TOML does, whether or not the operation stages: published ∩ entries still there)."""
        self._flag(folder)
        self.record_file(self.store.path(folder, TOML_NAME))

    def _touch(self, path: Path) -> None:
        root = self.store.path("", "")
        if path.parent != root and path.parent.is_relative_to(root):  # files outside images/ (README...) are not
            self.touched.add(path.parent.relative_to(root).as_posix())

    def __exit__(self, exc_type, exc, tb) -> bool:
        global _depth, _outer, _owner
        try:
            if exc_type is None and _depth == 1:
                try:
                    self.on_commit(self)
                    self.write_index()
                    force = self.stage_force
                    left = self.take_staged()
                    if left:
                        self.vcs.stage_add(left, force=force)
                except BaseException:
                    self._rollback()
                    raise
            elif exc_type is not None:
                self._rollback()
        finally:
            _depth -= 1
            if _depth == 0:
                _undo.clear()
                _outer = None
                _owner = None
            _LOCK.release()
        return False

    def _rollback(self) -> None:
        outer = _outer or self
        while len(_undo) > self._mark:
            path, data = _undo.pop()
            outer._indexes.discard(path)  # restored: a later write in the outer unit snapshots it again
            try:
                _restore(path, data)
            except OSError:
                pass  # best effort: keep restoring the rest, the original error is what the caller needs
