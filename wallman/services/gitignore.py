"""Keep images we may not redistribute out of git (port of legacy guard.py)."""
from __future__ import annotations

import operator
import posixpath
from pathlib import Path

from ..domain.licenses import SHAREABLE
from ..domain.rules import MEDIA_DIR
from ..ports import Catalogue

IMAGE = (".jpg", ".jpeg", ".png", ".gif", ".webp", ".tif", ".tiff", ".bmp", ".avif", ".heic")
BEGIN = "# >>> generated by wallman (just gitignore) — do not edit"
LEGACY_BEGIN = "# >>> generated by _tools/guard.py — do not edit"
END = "# <<< generated"
NOT_LISTED = "not listed in any wallpapers.toml"


def _entry_paths(folder: str, w) -> tuple[str, ...]:
    """The entry's file and original, relative to the repo root."""
    paths = (posixpath.normpath(posixpath.join(MEDIA_DIR, folder, w.file)),)
    if w.original:
        paths += (posixpath.normpath(posixpath.join(MEDIA_DIR, folder, w.original)),)
    return paths


def _folder_licenses(c) -> dict[str, str]:
    """path -> license for one collection (on a path listed twice, the later entry wins)."""
    out: dict[str, str] = {}
    for w in c.wallpapers:
        for p in _entry_paths(c.folder, w):
            out[p] = w.license
    return out


def _patched(folder: str, old: list, part: dict[str, str], ws: list) -> dict[str, str] | None:
    """`part` (computed from `old`) updated for the entries of `ws` that are not the very same objects as `old` at
    the same position, without visiting the others; None when that cannot be exact (entries added or removed, or
    a path listed twice: then which entry wins depends on positions)."""
    if len(old) != len(ws) or len(part) != sum(1 + bool(w.original) for w in old):
        return None
    changed = [k for k, same in enumerate(map(operator.is_, old, ws)) if not same]
    out = dict(part)
    for k in changed:
        for p in _entry_paths(folder, old[k]):
            del out[p]
    added = 0
    for k in changed:
        for p in _entry_paths(folder, ws[k]):
            out[p] = ws[k].license
            added += 1
    removed = sum(1 + bool(old[k].original) for k in changed)
    return out if len(out) == len(part) - removed + added else None


class GitignoreService:
    def __init__(self, root: Path, catalogue: Catalogue) -> None:
        self.root = Path(root)
        self.catalogue = catalogue
        # folder -> (the wallpapers it was computed from, its path -> license). Wallpaper objects are immutable and
        # the catalogue hands out the same ones until an entry changes, so an edit recomputes only the entries that
        # are not the very same objects as last time (a catalogue that copies them recomputes everything)
        self._memo: dict[str, tuple[list, dict[str, str]]] = {}

    def licenses(self) -> dict[str, str]:
        """path relative to the repo root -> license, for listed files (under images/) and their originals (resolved
        from the entry's folder; they live in <repo>/_originals/, outside images/). External collections skipped.
        Later folders win on a path listed twice (folders in catalogue order)."""
        out: dict[str, str] = {}
        memo: dict[str, tuple[list, dict[str, str]]] = {}
        for c in self.catalogue.collections():
            if c.external:
                continue
            hit = self._memo.get(c.folder)
            part = _patched(c.folder, hit[0], hit[1], c.wallpapers) if hit is not None else None
            if part is None:
                part = _folder_licenses(c)
            memo[c.folder] = (c.wallpapers, part)
            out.update(part)
        self._memo = memo
        return out

    def write(self) -> int:
        restricted = sorted(p for p, lic in self.licenses().items() if lic not in SHAREABLE)
        path = self.root / ".gitignore"
        text = path.read_text(encoding="utf-8") if path.exists() else ""
        marker = next((m for m in (BEGIN, LEGACY_BEGIN) if m in text), None)
        if marker:
            head, rest = text.split(marker, 1)
            tail = rest.split(END, 1)[1] if END in rest else ""
        else:
            head, tail = text, ""
        block = "\n".join([BEGIN, "# not redistributable: just fetch downloads them", *(f"/{p}" for p in restricted), END])
        path.write_text(head.rstrip("\n") + ("\n\n" if head.strip() else "") + block + "\n" + tail.lstrip("\n"),
                        encoding="utf-8")
        return len(restricted)

    def check_staged(self, staged: list[Path]) -> list[str]:
        """Refusal lines for staged images that may not be redistributed; empty list = OK. Paths are relative to the repo root."""
        lic = self.licenses()
        bad = []
        for p in staged:
            rel = p.relative_to(self.root).as_posix() if p.is_absolute() else p.as_posix()
            if not rel.lower().endswith(IMAGE):
                continue
            if lic.get(rel) not in SHAREABLE:
                bad.append(f"  {rel}  ({lic.get(rel, NOT_LISTED)})")
        if not bad:
            return []
        return ["✗ commit refused: these images may not be redistributed", *bad,
                "  → if you may share it: set its license (and source) in the folder's wallpapers.toml, then commit again",
                "  → otherwise keep it local: git rm --cached <file> (it is listed in .gitignore after the next sync)"]
